class Mahasiswa:
    total_mahasiswa = 0

    def __init__(self, nama, nim, angkatan):
        self.nama = nama
        self.nim = nim
        self.angkatan = angkatan
        Mahasiswa.total_mahasiswa += 1

    def tampilkan_biodata(self):
        print(f"Nama:    {self.nama}")
        print(f"Nim:     {self.nim}")
        print(f"Angkatan: {self.angkatan}")


def main():
    nama = input("Masukkan Namamu: ")
    nim = input("Masukkan NIM kamu: ")
    angkatan = input("Masukkan Tahun Angkatanmu: ")

    mhs = Mahasiswa(nama, nim, angkatan)
    mhs.tampilkan_biodata()
    print(f"\nTotal Mahasiswa {Mahasiswa.total_mahasiswa}")


main()

class DataMahasiswa:
    def __init__(self, nama=None, nilai=None):
        self._nama = nama
        self._nilai = nilai

    def get_nama(self):
        return self._nama

    def set_nama(self, nama):
        self._nama = nama

    def get_nilai(self):
        return self._nilai

    def set_nilai(self, nilai):
        self._nilai = nilai

    def hapus_data(self):
        self._nama = None
        self._nilai = None


def tampilkan_menu():
    print("\n===== Program OOP =====")
    print("1. Mendeklarasikan Objek")
    print("2. Menambahkan / Menampilkan Objek")
    print("3. Merubah Nilai Objek")
    print("4. Menghapus Objek")
    print("5. Keluar Dari Program")


def main():
    objek = DataMahasiswa()

    while True:
        tampilkan_menu()
        pilihan = input("\nMasukkan Pilihan Berupa Angka (1/2/3/4/5): ").strip()

        if pilihan == "1":
            nama = input("Masukkan Namamu: ")
            nilai = int(input("Masukkan Nilaimu: "))
            objek.set_nama(nama)
            objek.set_nilai(nilai)
            print("Data Berhasil Ditambahkan")

        elif pilihan == "2":
            print(f"Nama: {objek.get_nama()}")
            print(f"Nilai: {objek.get_nilai()}")

        elif pilihan == "3":
            target = input("Apa yang ingin diubah (Nama/Nilai): ").strip().lower()
            if target == "nama":
                nama_baru = input("Masukkan Nama: ")
                objek.set_nama(nama_baru)
                print("Data Nama Berhasil Dirubah")
            elif target == "nilai":
                nilai_baru = int(input("Masukkan Nilai: "))
                objek.set_nilai(nilai_baru)
                print("Data Nilai Berhasil Dirubah")
            else:
                print("Pilihan field tidak dikenali (pilih Nama atau Nilai).")

        elif pilihan == "4":
            objek.hapus_data()
            print("Data Berhasil Dihapus")

        elif pilihan == "5":
            print("Terima Kasih Sudah Menggunakan Program Saya")
            break

        else:
            print("Pilihan tidak valid. Masukkan angka 1 sampai 5.")


main()