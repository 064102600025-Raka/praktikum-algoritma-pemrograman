def tulis_biodata(nama_file, nama, umur, alamat, email, dosen_wali):
    file = open(nama_file, "w")
    file.write(f"Nama: {nama}\n")
    file.write(f"Umur: {umur}\n")
    file.write(f"Alamat: {alamat}\n")
    file.write(f"Email: {email}\n")
    file.write(f"Dosen Wali: {dosen_wali}\n")
    file.close()


def baca_biodata(nama_file):
    file = open(nama_file, "r")
    isi = file.read()
    file.close()
    print("\nBerikut Ini Data Kamu")
    print(isi, end="")


def main():
    nama = input("Masukkan Nama mu: ")
    umur = input("Masukkan Umur mu: ")
    alamat = input("Masukkan Alamatmu: ")
    email = input("Masukkan Emailmu: ")
    dosen_wali = input("Masukkan Dosen Walimu: ")

    nama_file = "Biodata.txt"
    tulis_biodata(nama_file, nama, umur, alamat, email, dosen_wali)
    baca_biodata(nama_file)


main()

def buat_dan_tulis_file(nama_file, nama, nim, angkatan):
    file = open(nama_file, "w")
    file.write(f"Nama: {nama}\n")
    file.write(f"NIM: {nim}\n")
    file.write(f"Angkatan: {angkatan}\n")
    file.close()
    print("\nFile Berhasil Dibuat")


def baca_file(nama_file):
    file = open(nama_file, "r")
    isi = file.read()
    file.close()
    print("\n" + isi, end="")


def tambah_teks_file(nama_file, nama_sahabat, catatan):
    file = open(nama_file, "a")
    file.write(f"Nama Sahabat: {nama_sahabat}\n")
    file.write(f"Catatan: {catatan}\n")
    file.close()
    print("\nData Berhasil Ditambahkan")


def tampilkan_menu():
    print("\n===== Program File Handling =====")
    print("1. Membuat dan Menulis File")
    print("2. Membaca File")
    print("3. Menambahkan Text Pada File")
    print("4. Keluar Dari Program")


def main():
    while True:
        tampilkan_menu()
        pilihan = input("\nMasukkan Pilihan Berupa Angka (1/2/3/4): ").strip()

        if pilihan == "1":
            nama_file = input("Masukkan Nama File: ").strip()
            nama = input("Masukkan Namamu: ")
            nim = input("Masukkan NIM kamu: ")
            angkatan = input("Masukkan tahun angkatanmu: ")
            buat_dan_tulis_file(nama_file, nama, nim, angkatan)

        elif pilihan == "2":
            nama_file = input("Masukkan Nama File: ").strip()
            baca_file(nama_file)

        elif pilihan == "3":
            nama_file = input("Masukkan Nama File: ").strip()
            nama_sahabat = input("Masukkan Nama Sahabatmu: ")
            catatan = input("Masukkan Catatan Tambahan kamu: ")
            tambah_teks_file(nama_file, nama_sahabat, catatan)

        elif pilihan == "4":
            print("Terima Kasih Sudah Menggunakan Program Saya")
            break

        else:
            print("Pilihan tidak valid. Silakan masukkan 1, 2, 3, atau 4.")


main()