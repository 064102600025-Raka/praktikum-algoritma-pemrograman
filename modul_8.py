def jumlah_berurut(sisa, urutan=1):
    if sisa <= 0:
        return 0
    bilangan = int(input(f"Masukkan bilangan ke-{urutan}: "))
    return bilangan + jumlah_berurut(sisa - 1, urutan + 1)


def main():
    jumlah = int(input("Masukkan Jumlah: "))
    hasil = jumlah_berurut(jumlah)
    print(f"Hasil dari penjumlahan adalah: {hasil}")


main()

def pangkat_rekursif(base, eksponen):
    if eksponen == 0:
        return 1
    elif eksponen > 0:
        return base * pangkat_rekursif(base, eksponen - 1)
    else:
        return 1 / pangkat_rekursif(base, -eksponen)


def jalankan_program():
    print("Ini merupakan program pemangkatan negatif dan positif, tekan enter untuk berhenti")
    masukan_angka = input("Masukkan Angka: ").strip()
    if masukan_angka == "":
        print("Program Selesai")
        return

    base = float(masukan_angka)
    if base.is_integer():
        base = int(base)

    eksponen = int(input("Masukkan Pangkatnya: "))
    hasil = pangkat_rekursif(base, eksponen)

    if isinstance(hasil, float) and hasil.is_integer():
        hasil = int(hasil)

    print(f"Hasilnya adalah: {hasil}\n")
    jalankan_program()


jalankan_program()