def apakah_prima(angka):
    if angka <= 1:
        return False
    for pembagi in range(2, int(angka ** 0.5) + 1):
        if angka % pembagi == 0:
            return False
    return True


def tampilkan_hasil_prima(angka):
    if apakah_prima(angka):
        print(f"{angka} adalah bilangan Prima")
    else:
        print(f"{angka} bukanlah bilangan Prima")


def main():
    bilangan = int(input("Masukkan angka: "))
    tampilkan_hasil_prima(bilangan)


main()

def tentukan_ordinal(angka):
    if angka % 100 in [11, 12, 13]:
        akhiran = "th"
    else:
        satuan = angka % 10
        if satuan == 1:
            akhiran = "st"
        elif satuan == 2:
            akhiran = "nd"
        elif satuan == 3:
            akhiran = "rd"
        else:
            akhiran = "th"
    return (angka, akhiran)


def main():
    print("Ordinal Number")
    print("ketik 0 untuk menghentikan program")
    while True:
        angka = int(input("masukkan angka: "))
        hasil = tentukan_ordinal(angka)
        print(hasil)
        if angka == 0:
            print("terima kasih telah menggunakan program saya")
            break


main()