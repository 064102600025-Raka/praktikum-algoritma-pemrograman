def bubble_sort(data):
    arr = data.copy()
    n = len(arr)
    for i in range(n):
        sudah_terurut = True
        for j in range(0, n - i - 1):
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                sudah_terurut = False
        if sudah_terurut:
            break
    return arr


def binary_search(data_terurut, target):
    kiri = 0
    kanan = len(data_terurut) - 1

    while kiri <= kanan:
        tengah = (kiri + kanan) // 2
        if data_terurut[tengah] == target:
            return tengah
        elif data_terurut[tengah] < target:
            kiri = tengah + 1
        else:
            kanan = tengah - 1

    return -1


def main():
    raw_input = input("Masukkan elemen angka (pisahkan dengan spasi): ").strip()
    data_awal = [int(x) for x in raw_input.split()]
    target = int(input("Masukkan angka yang dicari: "))

    data_sorted = bubble_sort(data_awal)
    indeks = binary_search(data_sorted, target)

    print(f"Data setelah diurutkan : {data_sorted}")
    if indeks != -1:
        print(f"Elemen {target} ditemukan pada indeks ke-{indeks} (setelah diurutkan).")
    else:
        print(f"Elemen {target} tidak ditemukan di dalam list.")


main()

def recursive_bubble_sort(arr, n=None):
    if n is None:
        n = len(arr)

    if n <= 1:
        return arr

    for i in range(n - 1):
        if arr[i] > arr[i + 1]:
            arr[i], arr[i + 1] = arr[i + 1], arr[i]

    return recursive_bubble_sort(arr, n - 1)


def main():
    raw_input = input("Masukkan angka yang ingin diurutkan (pisahkan dengan spasi): ").strip()
    angka_list = [int(x) for x in raw_input.split()]
    hasil = recursive_bubble_sort(angka_list.copy())
    print("List sebelum diurutkan :", angka_list)
    print("List setelah diurutkan:", hasil)


main()