ulang = "y"

while ulang.lower() == "y":
    bulan = 0
    while bulan < 1 or bulan > 12:
        bulan = int(input("Masukkan bulan (1-12): "))
        if bulan < 1 or bulan > 12:
            print("Input bulan tidak valid! Masukkan angka antara 1 sampai 12.")

    tahun = 0
    while tahun <= 0:
        tahun = int(input("Masukkan tahun (contoh: 2026): "))
        if tahun <= 0:
            print("Input tahun tidak valid! Masukkan tahun lebih dari 0.")

    # Cek tahun kabisat
    kabisat = (tahun % 400 == 0) or (tahun % 4 == 0 and tahun % 100 != 0)

    # Tentukan jumlah hari
    if bulan in [1, 3, 5, 7, 8, 10, 12]:
        jumlah_hari = 31
    elif bulan in [4, 6, 9, 11]:
        jumlah_hari = 30
    else:  # bulan == 2
        if kabisat:
            jumlah_hari = 29
        else:
            jumlah_hari = 28

    print(f"Jumlah hari pada bulan ke-{bulan} tahun {tahun} adalah {jumlah_hari} hari.")
    ulang = input("Apakah ingin menghitung lagi? (y/n): ")

for i in range(7, 0, -1):
    print(str(i) * i)